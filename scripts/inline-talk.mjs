#!/usr/bin/env node
// Inline public/talk.mjs into index.html's single inline module.
//
// WHY THIS EXISTS: Tide ships as one static file (no bundler, no build
// artifacts served). But the Talk logic (public/talk.mjs) is a real ES module
// so it can be unit-tested with `node --test` — the node tests import it
// directly, and it is the source of truth. This step copies that module into
// index.html at build time, wrapped in an IIFE assigned to `TalkMod`, so the
// browser runs the same code without a second network request.
//
//     node scripts/inline-talk.mjs      (then rehash — see `npm run build`)
//
// Idempotent: it replaces everything between the two markers each run. After
// editing talk.mjs you MUST re-run this (build/predeploy do it for you) or the
// inlined copy in index.html goes stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const htmlPath = join(root, "public", "index.html");
const modPath = join(root, "public", "talk.mjs");

const START = "//__TALK_INLINE_START__";
const END = "//__TALK_INLINE_END__";

const html = readFileSync(htmlPath, "utf8");
const mod = readFileSync(modPath, "utf8");

// Collect exported names (the surface the app references as TalkMod.<name>).
const names = [];
const re = /^export\s+(?:async\s+)?(?:function|const|class)\s+([A-Za-z_$][\w$]*)/gm;
let m;
while ((m = re.exec(mod)) !== null) names.push(m[1]);
if (names.length === 0) { console.error("inline-talk: no exports found in talk.mjs"); process.exit(1); }

// Strip the `export ` keyword — the declarations live inside the IIFE scope —
// and drop any `import` lines (talk.mjs has none, but guard anyway).
const stripped = mod
  .replace(/^export\s+/gm, "")
  .replace(/^import\s.*$/gm, "")
  .trim();

const block = [
  START + " (generated by scripts/inline-talk.mjs — edit public/talk.mjs, then `npm run build`)",
  "  const TalkMod = (() => {",
  stripped.split("\n").map((l) => (l ? "  " + l : l)).join("\n"),
  "  return { " + names.join(", ") + " };",
  "  })();",
  "  " + END,
].join("\n  ");

const startIdx = html.indexOf(START);
const endIdx = html.indexOf(END);
if (startIdx < 0 || endIdx < 0 || endIdx < startIdx) {
  console.error(`inline-talk: markers not found in index.html (${START} / ${END})`);
  process.exit(1);
}
const before = html.slice(0, startIdx);
const after = html.slice(endIdx + END.length);
const out = before + block.trimStart() + after;

if (out === html) { console.log("inline-talk: index.html already up to date"); process.exit(0); }
writeFileSync(htmlPath, out);
console.log(`inline-talk: inlined talk.mjs (${names.length} exports, ${Buffer.byteLength(stripped, "utf8")} bytes) into index.html`);
